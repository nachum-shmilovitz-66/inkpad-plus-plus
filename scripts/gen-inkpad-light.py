#!/usr/bin/env python3
"""MAC-80: generates Themes/Inkpad Light.xml — a calm, BBEdit-like light theme — from upstream's
stylers.model.xml, so it covers every language upstream styles. Each lexer style gets a colour by
what it is (comment, string, number, keyword, …); fonts are left to the Default Style (Menlo).
Regenerate rather than editing the XML:  python3 scripts/gen-inkpad-light.py
"""
import os
import re
import sys
import xml.etree.ElementTree as ET

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SOURCE = os.path.join(ROOT, "vendor/upstream/PowerEditor/src/stylers.model.xml")
OUTPUT = os.path.join(ROOT, "Themes/Inkpad Light.xml")

# The palette (RRGGBB).
TEXT, BACKGROUND = "000000", "FFFFFF"
BLUE = "2949C8"        # keywords, keys, types, tags, true/false/null
RED = "C3155A"         # strings and characters
ORANGE = "C55A11"      # numbers, entities
GRAY = "6E7781"        # comments
BROWN = "8A5300"       # preprocessor, attributes
PURPLE = "7A3E9D"      # variables, labels, regular expressions
ERROR = "D00000"

RULES = [  # first match wins; tested on the upper-cased style name
    (r"COMMENT", GRAY),
    (r"ERROR", ERROR),
    (r"STRING|CHARACTER|\bCHAR\b|VERBATIM|HEREDOC|TRIPLE|BACKTICK|TEMPLATE|QUOTED", RED),
    (r"REGEX", PURPLE),
    (r"NUMBER|NUMERIC|\bHEX\b|DIGIT", ORANGE),
    (r"PREPROCESSOR|DIRECTIVE|MACRO|PRAGMA", BROWN),
    (r"PROPERTY NAME|\bKEY\b", BLUE),
    (r"KEYWORD|INSTRUCTION|TYPE|\bWORD|RESERVED|BUILTIN|STATEMENT|COMMAND|\bTAG", BLUE),
    (r"ATTRIBUTE", BROWN),
    (r"ENTITY", ORANGE),
    (r"VARIABLE|LABEL", PURPLE),
    (r"DEFAULT|IDENTIFIER|OPERATOR", TEXT),
]

# Global styles: the editor's surroundings (name → attributes to set).
GLOBALS = {
    "Default Style": {"fgColor": TEXT, "bgColor": BACKGROUND, "fontName": "Menlo", "fontSize": "9", "fontStyle": "0"},
    "Indent guideline style": {"fgColor": "E8E8E8", "bgColor": BACKGROUND},
    "Brace highlight style": {"fgColor": TEXT, "bgColor": "DDE6FF", "fontStyle": "0"},
    "Bad brace colour": {"fgColor": ERROR, "bgColor": BACKGROUND},
    "Current line background colour": {"bgColor": "FFFBDD"},
    "Selected text colour": {"bgColor": "B5D5FF"},
    "Multi-selected text color": {"bgColor": "B5D5FF"},
    "Caret colour": {"fgColor": TEXT},
    "Edge colour": {"fgColor": "E8E8E8"},
    "Line number margin": {"fgColor": "9A9A9A", "bgColor": "F4F4F4", "fontName": "Menlo", "fontStyle": "0"},
    "Bookmark margin": {"bgColor": "F4F4F4"},
    "Fold": {"fgColor": "8E8E8E", "bgColor": "8E8E8E"},
    "Fold active": {"fgColor": "8E8E8E"},
    "Fold margin": {"fgColor": "F4F4F4", "bgColor": "F4F4F4"},
    "White space symbol": {"fgColor": "C8C8C8"},
}


def colour_for(name, upstream):
    upper = name.upper()
    for pattern, colour in RULES:
        if re.search(pattern, upper):
            return colour
    return upstream or TEXT


def main():
    tree = ET.parse(SOURCE)
    root = tree.getroot()
    for lexer in root.iter("LexerType"):
        for style in lexer.iter("WordsStyle"):
            style.set("fgColor", colour_for(style.get("name", ""), style.get("fgColor")))
            style.set("bgColor", BACKGROUND)
            style.set("fontName", "")
            style.set("fontSize", "")
            underline = int(style.get("fontStyle") or 0) & 4
            style.set("fontStyle", str(underline))
    missing = set(GLOBALS)
    for widget in root.iter("WidgetStyle"):
        name = widget.get("name")
        for key, value in GLOBALS.get(name, {}).items():
            widget.set(key, value)
        missing.discard(name)
    if missing:
        sys.exit(f"global styles not found upstream: {sorted(missing)}")
    os.makedirs(os.path.dirname(OUTPUT), exist_ok=True)
    body = ET.tostring(root, encoding="unicode")
    header = ('<?xml version="1.0" encoding="UTF-8" ?>\n'
              "<!-- Inkpad Light (MAC-80): generated by scripts/gen-inkpad-light.py — regenerate, do not edit. -->\n")
    with open(OUTPUT, "w", encoding="utf-8") as f:
        f.write(header + body + "\n")
    print(f"wrote {OUTPUT}")


if __name__ == "__main__":
    main()

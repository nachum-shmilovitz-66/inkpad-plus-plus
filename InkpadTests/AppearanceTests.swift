import XCTest
@testable import Inkpad

/// MAC-80: the clearer, BBEdit-like look — Inkpad Light by default, triangle folds, line spacing.
/// MAC-81: the full path in the window title.
final class AppearanceTests: XCTestCase {
    private var repo: URL { URL(fileURLWithPath: #filePath).deletingLastPathComponent().deletingLastPathComponent() }
    private var suite: String!
    private var defaults: UserDefaults!
    private var support: URL!

    override func setUpWithError() throws {
        suite = "app.inkpad.Inkpad.tests.appearance.\(UUID().uuidString)"  // a throwaway suite only
        defaults = UserDefaults(suiteName: suite)
        support = FileManager.default.temporaryDirectory.appendingPathComponent("AppearanceTests-\(UUID().uuidString)")
    }

    override func tearDownWithError() throws {
        defaults.removePersistentDomain(forName: suite)
        try? FileManager.default.removeItem(at: support)
        Preferences.update { $0 = Preferences() }
    }

    /// RRGGBB as Scintilla's BGR.
    private func bgr(_ hex: String) -> Int {
        let v = Int(hex, radix: 16)!
        return ((v >> 16) & 0xFF) | (v & 0xFF00) | ((v & 0xFF) << 16)
    }

    private func manager() -> ThemeManager { ThemeManager(defaults: defaults, supportDirectory: support) }

    // MARK: Inkpad Light

    func testInkpadLightIsTheThemeUntilAnotherIsPicked() {
        let themes = manager()
        XCTAssertTrue(themes.available.contains { $0.name == ThemeManager.preferredName }, "bundled")
        XCTAssertEqual(themes.selectedName, ThemeManager.preferredName, "nobody picked one yet")
        themes.select(ThemeManager.defaultName)
        XCTAssertEqual(manager().selectedName, ThemeManager.defaultName, "a picked theme stays picked")
        defaults.set("A Deleted Theme", forKey: "SelectedTheme")
        XCTAssertEqual(manager().selectedName, ThemeManager.defaultName, "a vanished pick falls back to the default")
    }

    func testInkpadLightCoversEveryLanguageUpstreamStyles() throws {
        let themes = manager()
        let light = themes.theme(named: ThemeManager.preferredName)
        let model = themes.theme(named: ThemeManager.defaultName)
        XCTAssertEqual(Set(light.lexerStyles.keys), Set(model.lexerStyles.keys))
        for (language, styles) in model.lexerStyles {
            XCTAssertEqual(light.lexerStyles[language]?.map(\.styleID), styles.map(\.styleID), language)
        }
    }

    func testTheLookIsMenloWithCalmColours() throws {
        let light = manager().theme(named: ThemeManager.preferredName)
        let base = try XCTUnwrap(light.global("Default Style"))
        XCTAssertEqual(base.fontName, "Menlo")
        XCTAssertEqual(base.fontSize, 9, "12 pt on screen with the 4/3 scaling")
        XCTAssertEqual(base.background, bgr("FFFFFF"))
        let json = try XCTUnwrap(light.lexerStyles["json"])
        func colour(_ name: String) -> Int? { json.first { $0.name == name }?.foreground }
        XCTAssertEqual(colour("PROPERTY NAME"), bgr("2949C8"), "keys blue")
        XCTAssertEqual(colour("KEYWORD"), bgr("2949C8"), "true/false/null blue")
        XCTAssertEqual(colour("STRING"), bgr("C3155A"), "strings red")
        XCTAssertEqual(colour("NUMBER"), bgr("C55A11"), "numbers orange")
        XCTAssertFalse(json.contains { $0.isBold || $0.fontName != nil }, "no bold, one font")
        XCTAssertEqual(light.lexerStyles["cpp"]?.first { $0.name == "COMMENT" }?.foreground, bgr("6E7781"), "comments gray")

        XCTAssertEqual(light.global("Current line background colour")?.background, bgr("FFFBDD"), "pale yellow")
        XCTAssertEqual(light.global("Line number margin")?.background, bgr("F4F4F4"), "a soft gray gutter")
        let margin = try XCTUnwrap(light.global("Fold margin"))
        XCTAssertEqual(margin.foreground, margin.background, "a solid fold margin, no checkerboard")
        XCTAssertNotEqual(light.global("Fold active")?.foreground, bgr("FF0000"), "no red fold line")
        XCTAssertEqual(light.global("Indent guideline style")?.foreground, bgr("E8E8E8"), "barely-there guides")
    }

    func testTheThemeIsGeneratedAndNamedRight() throws {
        let xml = try String(contentsOf: repo.appendingPathComponent("Themes/Inkpad Light.xml"), encoding: .utf8)
        XCTAssertTrue(xml.contains("generated by scripts/gen-inkpad-light.py"))
        let project = try String(contentsOf: repo.appendingPathComponent("project.yml"), encoding: .utf8)
        XCTAssertTrue(project.contains(#"cp "$PROJECT_DIR/Themes/"*.xml "$DEST/themes/""#), "bundled by the build")
    }

    // MARK: Preferences

    func testTheNewDefaults() throws {
        let p = Preferences()
        XCTAssertEqual(p.foldMarkStyle, .arrow)
        XCTAssertEqual(p.lineSpacing, 2)
        XCTAssertTrue(p.showFullPathInTitle)
        let old = try JSONDecoder().decode(Preferences.self, from: Data(#"{"caretWidth":2}"#.utf8))
        XCTAssertEqual(old.lineSpacing, 2, "settings saved before MAC-80 get the new defaults")
        XCTAssertTrue(old.showFullPathInTitle)
        var custom = Preferences()
        custom.lineSpacing = 0
        custom.showFullPathInTitle = false
        let back = try JSONDecoder().decode(Preferences.self, from: JSONEncoder().encode(custom))
        XCTAssertEqual(back.lineSpacing, 0)
        XCTAssertFalse(back.showFullPathInTitle)
    }

    func testLineSpacingIsSplitAboveAndBelow() {
        let tab = EditorTab(untitledNumber: 1)
        addTeardownBlock { tab.detach() }
        for (spacing, ascent, descent) in [(0, 0, 0), (2, 1, 1), (3, 2, 1), (6, 3, 3)] {
            var p = Preferences()
            p.lineSpacing = spacing
            EditorStyler.applyViewPreferences(p, theme: ThemeManager.shared.current, to: tab.editor)
            XCTAssertEqual(tab.editor.send(SCI_GETEXTRAASCENT), ascent, "spacing \(spacing)")
            XCTAssertEqual(tab.editor.send(SCI_GETEXTRADESCENT), descent, "spacing \(spacing)")
        }
    }

    func testTheSettingsWindowsNewControls() {
        let c = PreferencesController()
        XCTAssertEqual(c.lineSpacingPopup.itemTitles, ["None", "+1 px", "+2 px", "+3 px", "+4 px", "+6 px"])
        XCTAssertEqual(c.lineSpacingPopup.indexOfSelectedItem, 2)
        c.lineSpacingPopup.selectItem(at: 4)
        c.fullPathBox.state = .off
        c.controlChanged(nil)
        XCTAssertEqual(Preferences.current.lineSpacing, 4)
        XCTAssertFalse(Preferences.current.showFullPathInTitle)
    }

    // MARK: Full path (MAC-81)

    func testTheTitleShowsTheFullPath() {
        let home = "/Users/someone"
        let inHome = URL(fileURLWithPath: "/Users/someone/Downloads/rules.json")
        XCTAssertEqual(WindowTitle.text(displayName: "rules.json", fileURL: inHome, fullPath: true, home: home), "~/Downloads/rules.json")
        XCTAssertEqual(WindowTitle.text(displayName: "rules.json", fileURL: inHome, fullPath: false, home: home), "rules.json")
        XCTAssertEqual(WindowTitle.text(displayName: "hosts", fileURL: URL(fileURLWithPath: "/etc/hosts"), fullPath: true, home: home), "/etc/hosts")
        XCTAssertEqual(WindowTitle.text(displayName: "x", fileURL: URL(fileURLWithPath: "/Users/someoneelse/x"), fullPath: true, home: home),
                       "/Users/someoneelse/x", "a neighbour's folder is not ~")
        XCTAssertEqual(WindowTitle.text(displayName: "new 1", fileURL: nil, fullPath: true, home: home), "new 1", "untitled")
    }

    func testTheWindowTitleFollowsTheSetting() throws {
        let file = support.appendingPathComponent("title.txt")
        try FileManager.default.createDirectory(at: support, withIntermediateDirectories: true)
        try Data("x".utf8).write(to: file)
        let window = MainWindowController()
        addTeardownBlock { window.openTabs.forEach { $0.detach() } }
        window.open(file)
        XCTAssertEqual(window.window?.title, WindowTitle.text(displayName: "title.txt", fileURL: file, fullPath: true))
        XCTAssertTrue(window.window?.title.hasSuffix("/title.txt") ?? false)
        Preferences.update { $0.showFullPathInTitle = false }
        RunLoop.main.run(until: Date().addingTimeInterval(0.2))
        XCTAssertEqual(window.window?.title, "title.txt")
    }
}
